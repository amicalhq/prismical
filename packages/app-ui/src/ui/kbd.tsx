import { cn } from "../lib/utils"

// Vendored from shadcn/ui (`npx shadcn add kbd`) — the one key cap. Everything
// that advertises a shortcut goes through this: the sidebar hint chips
// (`shell/shortcut-hint.tsx`), the command-palette footer, and Settings →
// Shortcuts. Before it there were three hand-rolled `<kbd>` looks that had
// drifted apart on font, radius, border and opacity.

function Kbd({ className, ...props }: React.ComponentProps<"kbd">) {
  return (
    <kbd
      data-slot="kbd"
      className={cn(
        "pointer-events-none inline-flex h-5 w-fit min-w-5 items-center justify-center gap-1 rounded-sm bg-muted px-1 font-sans text-xs font-medium text-muted-foreground select-none",
        "[&_svg:not([class*='size-'])]:size-3",
        "[[data-slot=tooltip-content]_&]:bg-background/20 [[data-slot=tooltip-content]_&]:text-background dark:[[data-slot=tooltip-content]_&]:bg-background/10",
        className
      )}
      {...props}
    />
  )
}

function KbdGroup({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <kbd
      data-slot="kbd-group"
      className={cn("inline-flex items-center gap-1", className)}
      {...props}
    />
  )
}

export { Kbd, KbdGroup }
