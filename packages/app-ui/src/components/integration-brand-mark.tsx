/**
 * Branded integration tile shared by the catalog, connection details, and Skill tool picker.
 * Known catalog providers render their real SVG mark; custom MCP servers get a neutral monogram
 * instead of an unrelated emoji or remote image dependency.
 */
export function IntegrationLogo({ directoryKey, name, size = 'md' }: IntegrationLogoProps) {
  const hasBrandMark = directoryKey ? INTEGRATION_BRAND_KEYS.has(directoryKey) : false;
  const sizeClass =
    size === 'xs' ? 'size-7 text-2xs' : size === 'sm' ? 'size-9 text-xs' : 'size-10 text-sm';
  const markClass = size === 'xs' ? 'h-4 w-5' : size === 'sm' ? 'h-5 w-6' : 'h-6 w-7';

  return (
    <span
      aria-hidden="true"
      data-integration-logo={directoryKey ?? 'custom'}
      className={cn(
        'grid shrink-0 place-items-center rounded-xl border border-black/5 font-brand font-bold shadow-xs',
        sizeClass,
        hasBrandMark && 'bg-white'
      )}
      style={{
        background: hasBrandMark ? undefined : 'var(--secondary)',
        color: hasBrandMark ? undefined : 'var(--foreground)',
      }}
    >
      {hasBrandMark && directoryKey ? (
        <IntegrationBrandMark brand={directoryKey} className={markClass} />
      ) : (
        initials(name)
      )}
    </span>
  );
}
